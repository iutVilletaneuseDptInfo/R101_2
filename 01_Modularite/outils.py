def double(x):
    """Retourne le double de x.

    :param x: le nombre à doubler.
    :type x: int
    :returns: le double de x.
    :rtype: int"""
    return 2 * x


def triple(x):
    """Retourne le triple de x.

    :param x: le nombre à tripler.
    :type x: int
    :returns: le triple de x.
    :rtype: int"""
    return 3 * x
